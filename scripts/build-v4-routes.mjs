#!/usr/bin/env node
// Generates the /v4 route pages (conditions, privacy, inscription) from the
// existing Spanish sources: navigation rebased into /v4 except public /assets/
// media, root form preserved. inscription-v4.js preselects plan/billing from
// ?plan=&billing= (query wins) or the `pathwayV4Selection` session key; no
// live submission.
//
// Integration: build.mjs calls buildV4Routes({ outDir, rootDir }) after copying
// the v4 directory, so these pages replace the plain placeholders.

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve as resolvePath } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE_ORIGIN = 'https://pathway-languages.com';
const V4_PREFIX = '/v4';
const V4_DIRNAME = 'v4';
// Public media (videos, images) is shared at the site root; everything else
// that used to be root-relative is legacy root navigation and moves under /v4.
const PUBLIC_ROOT = '/assets/';

// Verbatim assets the copied pages need, copied from the repo root.
const VERBATIM_ASSETS = [
  'theme.css',
  'guide.css',
  'conditions-nclc7.css',
  'pathway-page-shell.css',
  'inscription.css',
  'inscription.js',
  'site-config.js',
  'pathway-mark.svg'
];

// Source page -> v4 page. Filenames are kept so existing /v4/*.html links work.
const PAGES = [
  { source: 'condiciones.html', target: 'condiciones.html', anchor: 'compromiso-nclc7' },
  { source: 'privacidad.html', target: 'privacidad.html' },
  { source: 'inscription.html', target: 'inscription.html', adapter: true }
];

const ADAPTER_ASSET = 'inscription-v4.js';
const INSCRIPTION_SCRIPT_MARKER = '<script src="inscription.js?v=20260831-stepper"></script>';
const SELECTION_STORAGE_KEY = 'pathwayV4Selection';

export const PLAN_VALUES = ['Esencial', 'Acelerado', 'Intensivo'];
export const BILLING_VALUES = ['Mensual', 'Ciclo'];
const PLAN_ALIASES = { esencial: 'Esencial', acelerado: 'Acelerado', intensivo: 'Intensivo' };
const BILLING_ALIASES = { mensual: 'Mensual', ciclo: 'Ciclo', monthly: 'Mensual', cycle: 'Ciclo' };

function normalizePreference(value, aliases, allowed) {
  if (value == null) return null;
  const key = String(value).trim().toLowerCase();
  if (!key) return null;
  const canonical = aliases[key];
  if (canonical && allowed.includes(canonical)) return canonical;
  return allowed.find((option) => option.toLowerCase() === key) || null;
}

// Query wins over the stored session; unknown values are ignored.
export function resolveEnrollPreferences(search, stored) {
  const params = new URLSearchParams(search || '');
  const plan = normalizePreference(params.get('plan'), PLAN_ALIASES, PLAN_VALUES)
    || normalizePreference(stored && stored.plan, PLAN_ALIASES, PLAN_VALUES)
    || null;
  const billing = normalizePreference(params.get('billing'), BILLING_ALIASES, BILLING_VALUES)
    || normalizePreference(stored && stored.billing, BILLING_ALIASES, BILLING_VALUES)
    || null;
  return { plan, billing };
}

// Emitted verbatim into the adapter so the tested resolver and shipped one match.
function adapterCore() {
  return [
    `const PLAN_VALUES = ${JSON.stringify(PLAN_VALUES)};`,
    `const BILLING_VALUES = ${JSON.stringify(BILLING_VALUES)};`,
    `const PLAN_ALIASES = ${JSON.stringify(PLAN_ALIASES)};`,
    `const BILLING_ALIASES = ${JSON.stringify(BILLING_ALIASES)};`,
    normalizePreference.toString(),
    resolveEnrollPreferences.toString()
  ].join('\n');
}

export function buildAdapterSource() {
  return `// Generated by scripts/build-v4-routes.mjs.
// Preselects the plan/billing the V4 flow requested via ?plan=&billing= or the
// session, so the existing inscription pathway reports the chosen rate.
(() => {
${adapterCore()}

  const STORAGE_KEY = '${SELECTION_STORAGE_KEY}';

  function readStored() {
    try { return JSON.parse(sessionStorage.getItem(STORAGE_KEY) || 'null'); }
    catch (_) { return null; }
  }

  function persist(resolved, stored) {
    try {
      sessionStorage.setItem(STORAGE_KEY, JSON.stringify({
        plan: resolved.plan || (stored && stored.plan) || null,
        billing: resolved.billing || (stored && stored.billing) || null
      }));
    } catch (_) { /* session storage is already used by the form; ignore failures */ }
  }

  function applyEnrollPreferences() {
    const form = document.querySelector('[data-enroll-form]');
    if (!form) return;
    const stored = readStored();
    const resolved = resolveEnrollPreferences(location.search, stored);
    const select = (name, value) => {
      if (!value) return;
      const input = [...form.querySelectorAll('input[type="radio"][name="' + name + '"]')]
        .find((candidate) => candidate.value === value);
      if (!input) return;
      input.checked = true;
      input.dispatchEvent(new Event('input', { bubbles: true }));
      input.dispatchEvent(new Event('change', { bubbles: true }));
    };
    select('plan', resolved.plan);
    select('billing', resolved.billing);
    persist(resolved, stored);
  }

  // Script follows the form markup, so apply now, before the form script runs.
  if (document.querySelector('[data-enroll-form]')) applyEnrollPreferences();
  else document.addEventListener('DOMContentLoaded', applyEnrollPreferences, { once: true });
})();
`;
}

// Spanish legal filename that must resolve to the real terms page we generate,
// not the localised placeholder at /v4/conditions-nclc7.html.
const CONDITIONS_REMAP = { 'conditions-nclc7.html': 'condiciones.html' };

// Rebase every local reference into the /v4 namespace: bare relative, site
// absolute, and root-relative navigation. Public /assets/ media stays at the
// root; anchors, external urls and already-namespaced /v4 paths are left alone.
export function rebaseHtml(html) {
  const escapedOrigin = SITE_ORIGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const withAbsolutes = html.replace(new RegExp(`${escapedOrigin}/(?!v4/)`, 'g'), `${SITE_ORIGIN}/v4/`);
  return withAbsolutes.replace(/(\s(?:href|src)=")([^"]*)(")/gi, (match, before, value, after) => {
    const raw = value.trim();
    if (!raw) return match;
    // Absolute schemes (http:, mailto:, data:), protocol-relative and anchors.
    if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i.test(raw)) return match;
    if (raw.startsWith('/')) {
      if (raw === '/') return `${before}${V4_PREFIX}/${after}`;
      if (raw.startsWith(PUBLIC_ROOT) || raw === V4_PREFIX || raw.startsWith(`${V4_PREFIX}/`)) return match;
      return `${before}${V4_PREFIX}${raw}${after}`;
    }
    let path = raw.replace(/^\.\//, '');
    if (path === 'index-v2.html' || path === 'index.html') path = '';
    // Keep localised variants (fr/…, en/…, de/…) but send the Spanish legal
    // filename to the real terms page we generate.
    else if (CONDITIONS_REMAP[path]) path = CONDITIONS_REMAP[path];
    return `${before}${V4_PREFIX}/${path}${after}`;
  });
}

function injectAdapter(html) {
  if (!html.includes(INSCRIPTION_SCRIPT_MARKER)) {
    throw new Error('Inscription script marker not found; cannot add the V4 rate adapter.');
  }
  return html.replace(
    INSCRIPTION_SCRIPT_MARKER,
    `<script src="${V4_PREFIX}/${ADAPTER_ASSET}"></script>\n  ${INSCRIPTION_SCRIPT_MARKER}`
  );
}

// Add an anchor id to the <h1> when the homepage deep-links a heading that the
// rebased source page does not carry, so the CTA lands on the real content.
function addHeadingAnchor(html, anchor) {
  if (html.includes(`id="${anchor}"`)) return html;
  return html.replace(/<h1(?![^>]*\bid=)/i, `<h1 id="${anchor}"`);
}

function transformPage(sourceHtml, page) {
  let html = page.adapter ? injectAdapter(sourceHtml) : sourceHtml;
  if (page.anchor) html = addHeadingAnchor(html, page.anchor);
  return rebaseHtml(html);
}

function sha256(content) {
  return createHash('sha256').update(content).digest('hex');
}

export async function buildV4Routes(options = {}) {
  const rootDir = resolvePath(options.rootDir || process.cwd());
  const outDir = resolvePath(options.outDir || join(rootDir, 'dist', 'client'));
  const v4Dir = join(outDir, V4_DIRNAME);
  await mkdir(v4Dir, { recursive: true });

  const files = [];
  async function emit(name, content) {
    const target = join(v4Dir, name);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content);
    files.push({ name, bytes: Buffer.byteLength(content), sha256: sha256(content) });
  }

  for (const asset of VERBATIM_ASSETS) {
    let content;
    try {
      content = await readFile(join(rootDir, asset));
    } catch (_) {
      throw new Error(`Missing source asset required by V4 routes: ${asset}`);
    }
    await emit(asset, content);
  }

  for (const page of PAGES) {
    let source;
    try {
      source = await readFile(join(rootDir, page.source), 'utf8');
    } catch (_) {
      throw new Error(`Missing source page required by V4 routes: ${page.source}`);
    }
    await emit(page.target, transformPage(source, page));
  }

  await emit(ADAPTER_ASSET, buildAdapterSource());

  return { rootDir, outDir, v4Dir, files };
}

const invokedDirectly = process.argv[1] && resolvePath(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const result = await buildV4Routes();
  console.log(`Built ${result.files.length} V4 route files in ${result.v4Dir}`);
  for (const file of result.files) console.log(`  ${file.name} ${file.bytes}B ${file.sha256.slice(0, 12)}`);
}
