function sha256(content) {
  return createHash('sha256').update(content).digest('hex');
}

export async function buildV4Routes(options = {}) {
  const rootDir = resolvePath(options.rootDir || process.cwd());
  const outDir = resolvePath(options.outDir || join(rootDir, 'dist', 'client'));
  const v4Dir = join(outDir, V4_DIRNAME);
  await mkdir(v4Dir, { recursive: true });

  const files = [];
  async function emit(name, content) {
    const target = join(v4Dir, name);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content);
    files.push({ name, bytes: Buffer.byteLength(content), sha256: sha256(content) });
  }

  for (const asset of VERBATIM_ASSETS) {
    let content;
    try {
      content = await readFile(join(rootDir, asset));
    } catch (_) {
      throw new Error(`Missing source asset required by V4 routes: ${asset}`);
    }
    await emit(asset, content);
  }

  for (const page of PAGES) {
    let source;
    try {
      source = await readFile(join(rootDir, page.source), 'utf8');
    } catch (_) {
      throw new Error(`Missing source page required by V4 routes: ${page.source}`);
    }
    await emit(page.target, transformPage(source, page));
  }

  await emit(ADAPTER_ASSET, buildAdapterSource());

  // Thank-you pages (promoted to the root by build-v4-default.mjs).
  for (const lang of ['es', 'fr', 'en', 'de']) {
    let homeMarkup;
    try { homeMarkup = await readFile(join(v4Dir, lang === 'es' ? '' : lang, 'index.html'), 'utf8'); }
    catch (_) { throw new Error(`V4 home (${lang}) must be built before the thank-you page.`); }
    await emit(`${lang === 'es' ? '' : `${lang}/`}${THANKS_PAGES[lang]}`, thanksPage(lang, homeMarkup));
  }

  return { rootDir, outDir, v4Dir, files };
}

