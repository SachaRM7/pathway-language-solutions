const CONDITIONS_REMAP = { 'conditions-nclc7.html': 'condiciones.html' };

// Rebase every local reference into the /v4 namespace: bare relative, site
// absolute, and root-relative navigation. Public /assets/ media stays at the
// root; anchors, external urls and already-namespaced /v4 paths are left alone.
export function rebaseHtml(html) {
  const escapedOrigin = SITE_ORIGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const withAbsolutes = html.replace(new RegExp(`${escapedOrigin}/(?!v4/)`, 'g'), `${SITE_ORIGIN}/v4/`);
  return withAbsolutes.replace(/(\s(?:href|src)=")([^"]*)(")/gi, (match, before, value, after) => {
    const raw = value.trim();
    if (!raw) return match;
    // Absolute schemes (http:, mailto:, data:), protocol-relative and anchors.
    if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i.test(raw)) return match;
    if (raw.startsWith('/')) {
      if (raw === '/') return `${before}${V4_PREFIX}/${after}`;
      if (raw.startsWith(PUBLIC_ROOT) || raw === V4_PREFIX || raw.startsWith(`${V4_PREFIX}/`)) return match;
      return `${before}${V4_PREFIX}${raw}${after}`;
    }
    let path = raw.replace(/^\.\//, '');
    if (path === 'index-v2.html' || path === 'index.html') path = '';
    // Keep localised variants (fr/…, en/…, de/…) but send the Spanish legal
    // filename to the real terms page we generate.
    else if (CONDITIONS_REMAP[path]) path = CONDITIONS_REMAP[path];
    return `${before}${V4_PREFIX}/${path}${after}`;
  });
}

function injectAdapter(html) {
  if (!html.includes(INSCRIPTION_SCRIPT_MARKER)) {
    throw new Error('Inscription script marker not found; cannot add the V4 rate adapter.');
  }
  return html.replace(
    INSCRIPTION_SCRIPT_MARKER,
    `<script src="${V4_PREFIX}/${ADAPTER_ASSET}"></script>\n  ${INSCRIPTION_SCRIPT_MARKER}`
  );
}

// Add an anchor id to the <h1> when the homepage deep-links a heading that the
// rebased source page does not carry, so the CTA lands on the real content.
function addHeadingAnchor(html, anchor) {
  if (html.includes(`id="${anchor}"`)) return html;
  return html.replace(/<h1(?![^>]*\bid=)/i, `<h1 id="${anchor}"`);
}

function transformPage(sourceHtml, page) {
  let html = page.adapter ? injectAdapter(sourceHtml) : sourceHtml;
  if (page.anchor) html = addHeadingAnchor(html, page.anchor);
  return rebaseHtml(html);
}

