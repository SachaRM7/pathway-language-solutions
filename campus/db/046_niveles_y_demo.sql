-- Pour un compte démo, une unité avec des brouillons compte comme publiée (accès, fin de niveau).
create or replace function pg_temp._patch_all(fn regprocedure, a text, b text, expect int) returns void
language plpgsql as $$
declare d text := pg_get_functiondef(fn); n int;
begin
  n := (length(d) - length(replace(d, a, ''))) / length(a);
  if n <> expect then raise exception 'patch %: % occurrence(s) of «%»', fn, n, left(a, 80); end if;
  execute replace(d, a, b);
end $$;
select pg_temp._patch_all('public.unit_access(uuid, text)',
  $x$e.status = 'validated'$x$, $x$(e.status = 'validated' or (e.status = 'draft' and public._is_demo(p_user)))$x$, 1);
select pg_temp._patch_all('public._level_units_done(uuid, text)',
  $x$e.status = 'validated'$x$, $x$(e.status = 'validated' or (e.status = 'draft' and public._is_demo(p_user)))$x$, 2);
